/**
 * Embeds WORKFLOW_API.md into a TS module so the `/llms.txt` route can serve it
 * on every target (Node, the Vercel esbuild bundle, Cloudflare Workers) without
 * runtime filesystem access. Single source of truth: WORKFLOW_API.md.
 *
 *   pnpm gen:llms
 *
 * Runs automatically in `vercel-build` so production is always current.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const md = readFileSync(join(root, "WORKFLOW_API.md"), "utf8");
const out = `// GENERATED by scripts/gen-llms.ts from WORKFLOW_API.md — DO NOT EDIT.
// Run \`pnpm gen:llms\` to regenerate after editing WORKFLOW_API.md.
export const LLMS_TXT = ${JSON.stringify(md)};
`;
writeFileSync(join(root, "src/http/llms-content.ts"), out);
// eslint-disable-next-line no-console
console.log(`gen:llms — wrote src/http/llms-content.ts (${md.length} bytes)`);
